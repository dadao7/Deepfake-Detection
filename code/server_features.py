def _has_word(text, words):
    """영문 단어 단위로 포함된 첫 단어 (예: 'bing' 이 'combing' 에 걸리지 않게)"""
    text = (text or '').lower()
    return next((w for w in words if re.search(r'(?<![a-z])' + re.escape(w) + r'(?![a-z])', text)), None)


def ai_vendor(*texts):
    """도구·서명자 이름 → 회사 이름 (모르면 None)"""
    text = ' '.join(t for t in texts if t)
    return next((name for name, words in AI_VENDORS if _has_word(text, words)), None)


def tool_text(mark):
    """'ChatGPT (gpt-image) · OpenAI' 처럼 만든 도구와 회사 이름"""
    generator, vendor = mark.get('generator'), mark.get('vendor')
    if generator and vendor and vendor.lower() not in generator.lower():
        return f'{generator} · {vendor}'
    return generator or vendor or '알 수 없는 도구'


def sniff_mime(head):
    """파일 앞부분으로 형식 판별 (확장자·Content-Type 보다 정확)"""
    if head[:8] == b'\x89PNG\r\n\x1a\n':
        return 'image/png'
    if head[:3] == b'\xff\xd8\xff':
        return 'image/jpeg'
    if head[:4] == b'RIFF' and head[8:12] == b'WEBP':
        return 'image/webp'
    if head[:6] in (b'GIF87a', b'GIF89a'):
        return 'image/gif'
    if head[4:8] == b'ftyp':
        brand = head[8:12]
        if brand in (b'heic', b'heix', b'mif1', b'msf1'):
            return 'image/heic'
        if brand in (b'avif', b'avis'):
            return 'image/avif'
        return 'video/quicktime' if brand == b'qt  ' else 'video/mp4'
    if head[:4] == b'\x1aE\xdf\xa3':
        return 'video/webm'
    return None


def _source_type(value):
    """IPTC 디지털 출처 유형 주소 → 이름 (예: .../digitalsourcetype/trainedAlgorithmicMedia)"""
    name = str(value).rstrip('/').rsplit('/', 1)[-1]
    return SOURCE_TYPE_NAMES.get(name.lower(), name)


def _manifest_info(manifest):
    """C2PA manifest 하나 → (출처 유형 목록, 만든 도구, 서명 정보)"""
    actions = []
    for assertion in manifest.get('assertions', []):
        if str(assertion.get('label', '')).startswith('c2pa.actions'):  # c2pa.actions, c2pa.actions.v2
            actions += (assertion.get('data') or {}).get('actions', [])
    source_types = [_source_type(a['digitalSourceType']) for a in actions if a.get('digitalSourceType')]

    created = next((a for a in actions if a.get('action') == 'c2pa.created'), actions[0] if actions else {})
    agent = created.get('softwareAgent')
    if isinstance(agent, dict):
        agent = f'{agent.get("name", "")} ({agent["version"]})' if agent.get('version') else agent.get('name')
    generator = agent or ((manifest.get('claim_generator_info') or [{}])[0].get('name')) or manifest.get('claim_generator')
    return source_types, generator, manifest.get('signature_info') or {}


def read_c2pa(stream, mime):
    """C2PA 출처 정보. 없거나 읽을 수 없으면 {'found': False}
    서명한 회사와 관계없이 읽음 (OpenAI·Google·Adobe·Microsoft 등). AI 여부는 IPTC 디지털 출처 유형으로 판단하고,
    편집 이력(이전 manifest)에 AI 생성이 기록된 경우도 찾음 (예: AI 이미지를 다른 프로그램에서 편집해 다시 서명)"""
    if c2pa is None or not mime:
        return {'found': False}
    try:
        with c2pa.Reader(mime, stream) as reader:
            store = json.loads(reader.json())
    except Exception:  # 출처 정보가 없거나 지원하지 않는 형식
        return {'found': False}

    manifests = store.get('manifests') or {}
    active = store.get('active_manifest')
    if not manifests.get(active):
        return {'found': False}
    infos = [_manifest_info(manifests[active])] + [_manifest_info(m) for label, m in manifests.items() if label != active]

    def first(types):  # 현재 manifest → 이전 편집 이력 순서로 해당 출처 유형을 찾음
        return next(((t, generator, sig) for kinds, generator, sig in infos for t in kinds if t in types), None)

    source_types, generator, signature = infos[0]
    kind, generator, signature = (first(AI_GENERATED_TYPES) or first(AI_EDITED_TYPES) or first(CAPTURE_TYPES) or
                                  (source_types[0] if source_types else None, generator, signature))
    state = store.get('validation_state')  # Valid / Trusted / Invalid

    return {
        'found': True,
        'ai_generated': kind in AI_GENERATED_TYPES,
        'ai_edited': kind in AI_EDITED_TYPES,
        'source_type': kind,
        'source_label': SOURCE_LABELS.get(kind, '출처 정보 있음'),
        'generator': generator,
        'vendor': ai_vendor(generator, signature.get('issuer')),
        'issuer': signature.get('issuer'),
        'signed_at': signature.get('time'),
        'signature_valid': state in ('Valid', 'Trusted'),
    }


# ── 1-2) 서명 없는 AI 표시 (XMP·PNG 텍스트·EXIF) ─────────────────────────────
# C2PA 처럼 서명이 없어 지우거나 바꾸기 쉽지만, AI 도구가 스스로 넣는 표시라 실제 사진에 있는 경우는 드묾
XMP_PACKET = re.compile(rb'<x:xmpmeta[\s\S]*?</x:xmpmeta>')
XMP_TOOL_FIELDS = ('Iptc4xmpExt:AISystemUsed', 'xmp:CreatorTool', 'tiff:Software')  # 도구 이름 칸
XMP_CREDIT_FIELDS = ('photoshop:Credit', 'Iptc4xmpCore:CreditLine')                   # 출처 문구 칸


def _xmp_value(xmp, name):
    """XMP 값: 속성(name="값") 또는 요소(<name>값</name>, 언어별 목록 rdf:li 안 포함)"""
    found = (re.search(re.escape(name) + r'\s*=\s*"([^"]*)"', xmp) or
             re.search('<' + re.escape(name) + r'>\s*(?:<rdf:\w+>\s*<rdf:li[^>]*>)?([^<]+)', xmp))
    value = H.unescape(found.group(1)).strip() if found else ''
    return value or None


def _mark(where, kind, tool=None, source_type=None):
    # kind: generated(AI 생성) / edited(AI 편집)
    return {'where': where, 'kind': kind, 'tool': tool, 'source_type': source_type}


def _xmp_marks(blob):
    """파일 안 XMP(JPEG·PNG·WebP·HEIC·MP4 공통): IPTC 디지털 출처 유형, AI 시스템 이름, 출처 문구"""
    marks = []
    for packet in XMP_PACKET.findall(blob):
        xmp = packet.decode('utf-8', errors='ignore')
        found = re.search(r'digitalsourcetype/(\w+)', xmp, re.I)
        source_type = _source_type(found.group(1)) if found else None
        ai_system = _xmp_value(xmp, 'Iptc4xmpExt:AISystemUsed')
        tools = ' '.join(v for v in (_xmp_value(xmp, f) for f in XMP_TOOL_FIELDS) if v)
        credit = ' '.join(v for v in (_xmp_value(xmp, f) for f in XMP_CREDIT_FIELDS) if v)
        if source_type in AI_GENERATED_TYPES:
            kind = 'generated'
        elif source_type in AI_EDITED_TYPES:
            kind = 'edited'
        elif source_type in CAPTURE_TYPES:  # 촬영 원본이라고 적혀 있으면 그대로 믿음
            kind = None
        elif _has_word(f'{tools} {credit}', AI_EDIT_WORDS):
            kind = 'edited'
        elif ai_system or _has_word(tools, AI_TOOL_WORDS) or _has_word(credit, AI_CREDIT_WORDS):
            kind = 'generated'
        else:
            kind = None
        if kind:
            credit_ai = _has_word(credit, AI_CREDIT_WORDS + AI_EDIT_WORDS)
            tool = ai_system or (credit if credit_ai else None) or _xmp_value(xmp, 'xmp:CreatorTool')
            marks.append(_mark('XMP', kind, tool, source_type))
    return marks


def _png_marks(img):
    """PNG 텍스트: Stable Diffusion WebUI·ComfyUI·InvokeAI·Fooocus·NovelAI 등이 생성 설정을 남김"""
    if img.format != 'PNG':
        return []
    text = getattr(img, 'text', None) or {}
    marks = []
    params = str(text.get('parameters', ''))
    if 'Steps:' in params and 'Sampler' in params:
        marks.append(_mark('PNG 생성 설정', 'generated', 'Stable Diffusion WebUI'))
    if '"class_type"' in str(text.get('prompt', '')) or '"nodes"' in str(text.get('workflow', '')):
        marks.append(_mark('PNG 생성 설정', 'generated', 'ComfyUI'))
    if any(key in text for key in ('invokeai_metadata', 'sd-metadata', 'Dream')):
        marks.append(_mark('PNG 생성 설정', 'generated', 'InvokeAI'))
    if 'fooocus_scheme' in text:
        marks.append(_mark('PNG 생성 설정', 'generated', 'Fooocus'))
    software = ' '.join(str(text.get(key, '')) for key in ('Software', 'Source'))
    if _has_word(software, AI_TOOL_WORDS):
        marks.append(_mark('PNG 텍스트', 'generated', text.get('Software') or text.get('Source')))
    return marks


def _exif_marks(img):
    """EXIF: 소프트웨어 이름(305), 사용자 설명(UserComment, Stable Diffusion WebUI 가 생성 설정을 넣음)"""
    exif = img.getexif()
    software = str(exif.get(305, '')).strip('\x00 ')
    marks = []
    if _has_word(software, AI_EDIT_WORDS):
        marks.append(_mark('EXIF', 'edited', software))
    elif _has_word(software, AI_TOOL_WORDS):
        marks.append(_mark('EXIF', 'generated', software))
    comment = exif.get_ifd(0x8769).get(0x9286)
    raw = (comment if isinstance(comment, bytes) else str(comment or '').encode()).replace(b'\x00', b'')
    if b'Steps:' in raw and b'Sampler' in raw:
        marks.append(_mark('EXIF 생성 설정', 'generated', 'Stable Diffusion WebUI'))
    return marks


def summarize_marks(marks):
    """찾은 표시 중 가장 강한 것 (AI 생성 > AI 편집) → {'found', 'ai_generated', 'ai_edited', ...}"""
    mark = next((m for m in marks if m['kind'] == 'generated'), None) or next(iter(marks), None)
    if not mark:
        return {'found': False}
    generated = mark['kind'] == 'generated'
    return {
        'found': True,
        'ai_generated': generated,
        'ai_edited': not generated,
        'source_type': mark['source_type'],
        'source_label': SOURCE_LABELS.get(mark['source_type']) or ('AI 생성 이미지' if generated
                                                                   else 'AI로 일부를 편집한 이미지'),
        'generator': mark['tool'],
        'vendor': ai_vendor(mark['tool']),
        'where': mark['where'],
    }


def read_ai_marks(data):
    """이미지 바이트 → 서명 없는 AI 표시"""
    marks = _xmp_marks(data)
    try:
        img = Image.open(io.BytesIO(data))
        marks += _png_marks(img) + _exif_marks(img)
    except Exception:  # PIL 이 못 여는 형식(HEIC 등)은 XMP 만 확인
        pass
    return summarize_marks(marks)


def read_ai_marks_file(path, chunk=4 * 1024 * 1024):
    """영상 파일 → XMP 의 AI 표시 (영상 메타데이터는 보통 파일 앞이나 끝에 있어 앞·뒤 4MB 만 확인)"""
    size = os.path.getsize(path)
    with open(path, 'rb') as fp:
        head = fp.read(chunk)
        tail = b''
        if size > chunk:
            fp.seek(max(chunk, size - chunk))
            tail = fp.read()
    return summarize_marks(_xmp_marks(head) + _xmp_marks(tail))


def read_exif(data):
    """EXIF 촬영 정보와 이미지 크기 (PIL 이 읽을 수 있는 형식만)"""
    try:
        img = Image.open(io.BytesIO(data))
        exif = img.getexif()
        clean = lambda v: str(v).strip('\x00 ').strip()
        info = {name: clean(exif[tag]) for tag, name in EXIF_TAGS.items() if exif.get(tag)}
        original = exif.get_ifd(0x8769).get(36867)
        if original:
            info['datetime_original'] = clean(original)
        return info, img.size
    except Exception:
        return {}, None


def inspect_metadata(data=None, path=None, mime_hint=None):
    """업로드한 원본 파일의 메타데이터. 이미지는 data(바이트), 영상은 path(임시 파일)"""
    if data is not None:
        mime = sniff_mime(data[:16]) or mime_hint
        exif, size = read_exif(data)
        meta = {'format': mime, 'file_size': len(data), 'exif': exif,
                'c2pa': read_c2pa(io.BytesIO(data), mime), 'ai_marks': read_ai_marks(data)}
        if size:
            meta['width'], meta['height'] = size
        return meta

    with open(path, 'rb') as fp:
        mime = sniff_mime(fp.read(16)) or mime_hint
        fp.seek(0)
        return {'format': mime, 'file_size': os.path.getsize(path), 'exif': {}, 'c2pa': read_c2pa(fp, mime),
                'ai_marks': read_ai_marks_file(path)}


