def heatmap_peaks(heat, margin, k=3, min_dist=2):
    """의심 영역 지도에서 강한 곳 k개 → [(얼굴 부위, 강도)] (같은 부위는 한 번만)"""
    h, w = heat.shape
    work = heat.copy()
    parts = []
    for _ in range(k):
        idx = int(np.argmax(work))
        y, x = divmod(idx, w)
        strength = float(work[y, x])
        if strength <= 0:
            break
        part = face_part((x + 0.5) / w, (y + 0.5) / h, margin)
        if part not in [p for p, _ in parts]:
            parts.append((part, strength))
        work[max(0, y - min_dist):y + min_dist + 1, max(0, x - min_dist):x + min_dist + 1] = -1
    return parts


