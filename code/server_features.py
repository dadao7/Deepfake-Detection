def check_public_url(url):
    """http(s) 이고 인터넷(공인) 주소인지 확인. 서버가 ngrok 으로 열려 있으므로 내부망 접근을 막음"""
    parsed = urllib.parse.urlparse(url)
    if parsed.scheme not in ('http', 'https') or not parsed.hostname:
        raise ValueError('http:// 또는 https:// 로 시작하는 주소를 입력해 주세요.')
    try:
        infos = socket.getaddrinfo(parsed.hostname, parsed.port or (443 if parsed.scheme == 'https' else 80))
    except socket.gaierror:
        raise ValueError('주소를 찾을 수 없습니다. 주소를 다시 확인해 주세요.')
    for info in infos:
        if not ipaddress.ip_address(info[4][0].split('%')[0]).is_global:
            raise ValueError('내부 네트워크 주소는 분석할 수 없습니다.')


class _CheckedRedirect(urllib.request.HTTPRedirectHandler):
    """리다이렉트로 내부망 주소로 넘어가는 것도 막음"""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        check_public_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


_OPENER = urllib.request.build_opener(_CheckedRedirect)


def download(url, user_agent=USER_AGENT):
    """URL 내용 받기 → (바이트, Content-Type, 최종 주소). 종류별 최대 크기 제한"""
    check_public_url(url)
    request = urllib.request.Request(url, headers={'User-Agent': user_agent, 'Accept': '*/*',
                                                   'Accept-Language': 'ko,en;q=0.8'})
    try:
        with _OPENER.open(request, timeout=URL_TIMEOUT) as resp:
            ctype = resp.headers.get_content_type()
            limit = (MAX_VIDEO_BYTES if ctype.startswith('video/') else
                     MAX_PAGE_BYTES if ctype in HTML_TYPES else MAX_IMAGE_BYTES)
            data = resp.read(limit + 1)
            final_url = resp.geturl()
    except urllib.error.HTTPError as e:
        if e.code == 429:
            raise ValueError('요청이 많아 사이트가 잠시 막았습니다. 잠시 후 다시 시도해 주세요.')
        raise ValueError(f'주소에서 파일을 받지 못했습니다 (HTTP {e.code}). 로그인이 필요한 페이지일 수 있습니다.')
    except (urllib.error.URLError, OSError) as e:
        raise ValueError(f'주소에 연결하지 못했습니다 ({getattr(e, "reason", e)}).')
    if len(data) > limit:
        raise ValueError(f'파일이 너무 큽니다 (최대 {limit // 1024 // 1024}MB).')
    return data, ctype, final_url


class _MetaParser(HTMLParser):
    """웹페이지의 og:image, og:video, <title> 추출"""

    def __init__(self):
        super().__init__()
        self.meta, self.title, self._in_title = {}, None, False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'meta':
            key = (attrs.get('property') or attrs.get('name') or '').lower()
            if key and attrs.get('content') and key not in self.meta:
                self.meta[key] = attrs['content']
        elif tag == 'title':
            self._in_title = True

    def handle_endtag(self, tag):
        if tag == 'title':
            self._in_title = False

    def handle_data(self, data):
        if self._in_title and self.title is None and data.strip():
            self.title = data.strip()


PAGE_MEDIA_KEYS = ('og:video:secure_url', 'og:video:url', 'og:video', 'og:image:secure_url', 'og:image',
                   'og:image:url', 'twitter:image', 'twitter:image:src')


def _parse_page(text):
    parser = _MetaParser()
    parser.feed(text)
    return parser


def _page_media(parser, base_url):
    """페이지의 대표 영상·이미지 주소 (우선순위 순서, 중복 제거)"""
    return list(dict.fromkeys(urllib.parse.urljoin(base_url, parser.meta[k]) for k in PAGE_MEDIA_KEYS
                              if parser.meta.get(k)))


def _html(url, user_agent):
    """웹페이지 HTML 문자열 (웹페이지가 아니면 빈 문자열)"""
    data, ctype, _ = download(url, user_agent)
    return data.decode('utf-8', errors='ignore') if ctype in HTML_TYPES else ''


def _page_meta(url, user_agent):
    return _parse_page(_html(url, user_agent)).meta


def _og_video(meta):
    return meta.get('og:video:secure_url') or meta.get('og:video') or meta.get('og:video:url')


# ── 2-1) 인스타그램 게시물 ────────────────────────────────────────────────
# 인스타그램 게시물 페이지는 로그인하지 않으면 내용이 없는 빈 화면이라, 메신저의 링크 미리보기와 같은 방식으로
# 공개 게시물만 받음 (공식 API 가 아니라서 인스타그램이 구조를 바꾸면 동작하지 않을 수 있음)
#   1) 퍼가기(embed) 페이지: 원본 크기 사진(1080px 이상), 여러 장 게시물의 사진 목록, 영상 여부
#   2) 영상 게시물: 게시물 페이지의 영상 주소(og:video). 릴스는 영상 주소를 주지 않아 대표 이미지(썸네일)로 분석
#   3) 게시자가 퍼가기를 막은 게시물: 게시물 페이지의 미리보기 이미지(og:image, 640px 정사각형 또는 400px)
# 비공개 계정·삭제·연령 제한 게시물, 스토리는 로그인이 필요해 분석할 수 없음
INSTAGRAM_HOSTS = ('instagram.com', 'instagr.am')
INSTAGRAM_POST = re.compile(r'^/(?:[\w.]+/)?(p|reels?|tv)/([\w-]+)')
POST_MAX_ITEMS = 10  # 여러 장 게시물에서 분석할 최대 사진 수 (여러 장 분석의 최대 장수와 같음)


def instagram_post(url):
    """인스타그램 게시물·릴스 주소 → (종류, 코드, 몇 번째 사진). 인스타그램 주소가 아니면 None"""
    parsed = urllib.parse.urlparse(url)
    host = (parsed.hostname or '').lower()
    if not any(host == h or host.endswith('.' + h) for h in INSTAGRAM_HOSTS):
        return None
    path = parsed.path
    if path.startswith('/share/'):  # 공유용 짧은 주소 → 실제 게시물 주소로 이동
        path = urllib.parse.urlparse(download(url, PREVIEW_UA)[2]).path
    found = INSTAGRAM_POST.match(path)
    if not found:
        if path.startswith('/stories/'):
            raise ValueError('스토리는 로그인이 필요해 분석할 수 없습니다. 게시물이나 릴스 링크를 넣어 주세요.')
        raise ValueError('인스타그램 게시물·릴스 링크를 넣어 주세요. (게시물의 공유 → 링크 복사)')
    kind = 'reel' if found.group(1).startswith('reel') else found.group(1)
    index = urllib.parse.parse_qs(parsed.query).get('img_index', [''])[0]  # 여러 장 중 보고 있던 사진 (1부터)
    return kind, found.group(2), int(index) if index.isdigit() else None


def _embed_media(page):
    """퍼가기 페이지 안의 게시물 정보(JSON). 여러 장·영상 게시물에만 있음"""
    found = re.search(r'"contextJSON":', page)
    if not found:
        return None
    try:
        context, _ = json.JSONDecoder().raw_decode(page, found.end())
        context = json.loads(context) if isinstance(context, str) else context  # JSON 이 문자열로 한 번 더 감싸져 있음
        return ((context or {}).get('gql_data') or {}).get('shortcode_media')
    except (ValueError, AttributeError):
        return None


def _embed_image(page):
    """퍼가기 페이지의 사진 (사진 한 장 게시물, 자르지 않은 원본 크기)"""
    tag = re.search(r'<img[^>]*EmbeddedMediaImage[^>]*>', page)
    src = tag and re.search(r'\ssrc="([^"]+)"', tag.group(0))
    return H.unescape(src.group(1)) if src else None


def _embed_owner(page):
    found = re.search(r'class="UsernameText"[^>]*>([^<]+)<', page)
    return H.unescape(found.group(1)).strip() if found else None


def _largest(node):
    """여러 크기 중 가장 큰 사진 주소"""
    sizes = node.get('display_resources') or []
    return max(sizes, key=lambda s: s.get('config_width', 0), default={}).get('src') or node.get('display_url')


def _thumbnail(node):
    """앱 목록에 보여 줄 작은 사진 주소 (640px 안팎)"""
    sizes = sorted(node.get('display_resources') or [], key=lambda s: s.get('config_width', 0))
    return next((s['src'] for s in sizes if s.get('config_width', 0) >= 320), None) or _largest(node)


def fetch_instagram(kind, code, index=None, face_check=None, single=False):
    """인스타그램 게시물 → fetch_media 와 같은 형식. 여러 장 게시물은 {'kind': 'batch', 'items': [{name, url, thumb}]}"""
    page_url = f'https://www.instagram.com/{"reel" if kind == "reel" else "p"}/{code}/'
    embed = _html(f'https://www.instagram.com/p/{code}/embed/captioned/', PREVIEW_UA)
    media = _embed_media(embed) or {}
    owner = (media.get('owner') or {}).get('username') or _embed_owner(embed)
    info = {'page_url': page_url, 'site': 'instagram',
            'page_title': f'인스타그램 @{owner} 게시물' if owner else '인스타그램 게시물'}

    def result(media_kind, url, notice=None):
        data, ctype, final_url = download(url)
        mime = sniff_mime(data[:16]) or ctype
        if not mime.startswith(media_kind + '/'):
            raise ValueError('게시물의 사진·영상 파일을 받지 못했습니다.')
        return {'kind': media_kind, 'data': data, 'mime': mime, 'media_url': final_url, 'notice': notice, **info}

    # 1) 여러 장 게시물: 사진 목록 → 여러 장 분석 (영상은 빼고 최대 10장)
    nodes = [edge['node'] for edge in (media.get('edge_sidecar_to_children') or {}).get('edges', [])]
    photos = [(pos, node) for pos, node in enumerate(nodes, 1) if not node.get('is_video')]
    if photos and not single:
        notes = []
        if len(photos) < len(nodes):
            notes.append(f'영상 {len(nodes) - len(photos)}개는 빼고 사진만 분석합니다.')
        if len(photos) > POST_MAX_ITEMS:
            notes.append(f'사진 {len(photos)}장 중 앞의 {POST_MAX_ITEMS}장만 분석합니다.')
        items = [{'name': f'{pos}/{len(nodes)}번째', 'url': _largest(node), 'thumb': _thumbnail(node)}
                 for pos, node in photos[:POST_MAX_ITEMS]]
        return {'kind': 'batch', 'items': items, 'media_url': page_url, 'notice': ' '.join(notes) or None, **info}
    if nodes:  # 한 장만: 링크에 적힌 번째(img_index) 또는 첫 번째 사진
        pos = index if index and index <= len(nodes) else (photos[0][0] if photos else 1)
        node = nodes[pos - 1]
        if node.get('is_video') and node.get('video_url') and not single:  # 영상만 있는 여러 장 게시물
            return result('video', node['video_url'], f'여러 장 게시물의 {pos}번째 영상을 분석했습니다.')
        what = '영상의 대표 이미지를' if node.get('is_video') else '사진을'
        return result('image', _largest(node), f'여러 장 게시물의 {pos}번째 {what} 분석했습니다.')

    # 2) 영상 게시물(릴스 포함): 게시물 페이지의 영상 주소. 없으면(릴스) 대표 이미지
    if media.get('is_video'):
        video_url = None if single else _og_video(_page_meta(page_url, PREVIEW_UA))
        if video_url:
            return result('video', video_url)
        return result('image', _largest(media),
                      '여러 장 분석에서는 영상 대신 대표 이미지(썸네일)로 분석했습니다.' if single else
                      '릴스 영상은 로그인 없이 받을 수 없어 대표 이미지(썸네일)로 분석했습니다.')

    # 3) 사진 한 장 게시물: 퍼가기 페이지의 원본 크기 사진
    src = _largest(media) if media else _embed_image(embed)
    if src:
        return result('image', src)

    # 4) 게시자가 퍼가기를 막은 게시물: 게시물 페이지의 미리보기 이미지
    #    640px 정사각형으로 자른 것 → 얼굴이 안 보이면 자르지 않은 400px 이미지
    meta = _page_meta(page_url, PREVIEW_UA)
    if _og_video(meta) and not single:
        return result('video', _og_video(meta))
    notice = ('게시자가 퍼가기를 막아 둔 게시물이라 미리보기 이미지(저해상도)로 분석했습니다. '
              '여러 장 게시물이면 첫 번째 사진만 분석됩니다.')
    first = None
    for get_image in (lambda: meta.get('og:image'),
                      lambda: _page_meta(page_url, PREVIEW_UA_UNCROPPED).get('og:image')):
        image_url = get_image()
        if not image_url:
            continue
        try:
            candidate = result('image', image_url, notice)
        except ValueError:
            continue
        if face_check is None or face_check(candidate['data']):
            return candidate
        first = first or candidate
    if first:
        return first
    raise ValueError('인스타그램 게시물을 불러오지 못했습니다. 비공개 계정·삭제된 게시물·연령 제한 게시물은 '
                     '로그인 없이 볼 수 없어 분석할 수 없습니다.')


def fetch_media(url, face_check=None, single=False):
    """링크 → {'kind': 'image'|'video', 'data', 'mime', 'media_url', 'page_url', 'page_title', 'site', 'notice'}
    - 인스타그램 게시물: 전용 방법(fetch_instagram). 여러 장 게시물은 {'kind': 'batch', 'items': [...]}
      single=True 면 여러 장·영상 게시물도 사진 한 장으로 받음 (여러 장 분석에 링크로 넣은 경우)
    - 이미지·영상 주소: 바로 받음
    - 웹페이지(기사·SNS): 대표 영상/이미지(og 태그). 없으면 링크 미리보기 봇으로 다시 요청
    face_check(바이트) → 얼굴이 보이는지 (미리보기 이미지가 여러 개일 때 고르는 데 사용)"""
    post = instagram_post(url)
    if post:
        return fetch_instagram(*post, face_check=face_check, single=single)

    data, ctype, final_url = download(url)
    page_url = page_title = None

    if sniff_mime(data[:16]) is None and ctype in HTML_TYPES:
        page_url, parser = final_url, _parse_page(data.decode('utf-8', errors='ignore'))
        if not _page_media(parser, page_url):  # SNS 처럼 링크 미리보기 봇에게만 대표 이미지를 알려 주는 사이트
            try:
                bot = _parse_page(_html(url, PREVIEW_UA))
                if _page_media(bot, page_url):
                    parser = bot
            except ValueError:
                pass
        page_title = parser.meta.get('og:title') or parser.title
        candidates = _page_media(parser, page_url)
        if not candidates:
            raise ValueError('이 페이지에서 대표 이미지나 영상을 찾지 못했습니다. 이미지 자체 주소를 넣어 보세요.')

        error = None
        for candidate in candidates:
            try:
                data, ctype, final_url = download(candidate)
            except ValueError as e:
                error = e
                continue
            if sniff_mime(data[:16]):
                break
        else:
            raise error or ValueError('페이지의 대표 이미지를 받지 못했습니다.')

    mime = sniff_mime(data[:16]) or ctype
    if mime.startswith('image/'):
        kind = 'image'
    elif mime.startswith('video/'):
        kind = 'video'
    else:
        raise ValueError('이미지나 영상 파일이 아닌 주소입니다.')
    return {'kind': kind, 'data': data, 'mime': mime, 'media_url': final_url,
            'page_url': page_url, 'page_title': page_title, 'site': None, 'notice': None}


# ── 3) 히트맵 시각화 ─────────────────────────────────────────────────────
def heatmap_overlay(face_bgr, heat):
    """얼굴 사진 위에 의심 영역 지도를 겹침 (빨강일수록 강함). heat: 0~1 확률 지도(작은 크기)"""
    h, w = face_bgr.shape[:2]
    heat = cv2.resize(heat.astype(np.float32), (w, h), interpolation=cv2.INTER_CUBIC)
    norm = np.clip((heat - heat.min()) / (heat.max() - heat.min() + 1e-6), 0, 1)
    color = cv2.applyColorMap((norm * 255).astype(np.uint8), cv2.COLORMAP_JET)
    alpha = (0.15 + 0.55 * norm)[..., None]
    return (face_bgr * (1 - alpha) + color * alpha).astype(np.uint8)


def face_part(px, py, margin):
    """히트맵 위치(얼굴 crop 기준 0~1) → 대략적인 얼굴 부위 (Haar 얼굴 박스 기준 비율로 추정)"""
    pad = margin / (1 + 2 * margin)  # crop 안에서 얼굴 박스가 시작하는 위치
    fx, fy = (px - pad) / (1 - 2 * pad), (py - pad) / (1 - 2 * pad)
    if not (0 <= fx <= 1 and 0 <= fy <= 1):
        return '얼굴 경계·배경'
    if fx < 0.12 or fx > 0.88:
        return '얼굴 옆 경계'
    if fy < 0.28:
        return '이마·머리선'
    if fy < 0.52:
        return '눈 주변'
    if fy < 0.70:
        return '코 주변' if 0.3 <= fx <= 0.7 else '볼(피부)'
    if fy < 0.90:
        return '입 주변' if 0.25 <= fx <= 0.75 else '턱선'
    return '턱·얼굴 아래 경계'


